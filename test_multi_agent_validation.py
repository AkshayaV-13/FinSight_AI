class Skip(Exception):
    pass


def test(name, kind, *categories):
    def register(function):
        TESTS.append((name, kind, categories, function))
        return function
    return register


def expect(condition, message):
    if not condition:
        raise AssertionError(message)


def no_fail(issues, label=""):
    bad = val.failures(issues)
    expect(not bad, f"{label} unexpected FAIL(s): " + "; ".join(
        f"[{i['check']}/{i['metric']}] {i['message']}" for i in bad))


def must_fail(issues, check_prefix, label=""):
    hits = [i for i in val.failures(issues) if i["check"].startswith(check_prefix)]
    expect(hits, f"{label} the validator did NOT fail '{check_prefix}' on bad input "
                 f"(issues: {[i['check'] for i in issues]})")


