@test("Agent 1 structural validator passes good records and fails bad ones", "unit (validator)",
      "Agent 1 structural validation")
def validator_agent1_structure():
    good = make_year("Apple", "2024", FULL)
    no_fail(val.validate_agent1_records(good, "Apple", "2024"))

    bad = copy.deepcopy(good); bad["revenue"]["evidence"] = None
    must_fail(val.validate_agent1_records(bad, "Apple", "2024"), "agent1.found", "FOUND without evidence")
    bad = copy.deepcopy(good); bad["eps"] = make_record("Apple", "2024", "eps", None); bad["eps"]["value"] = 6.08
    must_fail(val.validate_agent1_records(bad, "Apple", "2024"), "agent1.not_found", "NOT_FOUND carrying a value")
    bad = copy.deepcopy(good); bad["revenue"]["company"] = "Microsoft"
    must_fail(val.validate_agent1_records(bad, "Apple", "2024"), "agent1.identity", "wrong company")
    bad = copy.deepcopy(good); bad["revenue"]["status"] = "maybe"
    must_fail(val.validate_agent1_records(bad, "Apple", "2024"), "agent1.status", "invalid status")
    bad = copy.deepcopy(good); del bad["revenue"]["unit"]
    must_fail(val.validate_agent1_records(bad, "Apple", "2024"), "agent1.structure", "missing field")
    bad = copy.deepcopy(good); bad["revenue"]["page_number"] = None
    must_fail(val.validate_agent1_records(bad, "Apple", "2024"), "agent1.found", "FOUND without page")
    no_fail(val.validate_agent1_records(make_year("Apple", "2024", {}), "Apple", "2024"), "all NOT_FOUND")


