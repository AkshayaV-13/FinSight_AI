@test("invalid input, the ingest hook, and the existing-scripts helper", "unit (mock Agent 1)",
      "Orchestration", "Error handling")
def unit_input_and_ingest():
    pipe = Pipeline(FULL, FULL)
    bad = orch.run_financial_analysis("", "2024", "2023", extractor=pipe.extractor, analyzer=pipe.analyzer,
                                      red_flagger=pipe.red_flagger, verbose=False)
    expect(bad["status"] == "invalid_input" and pipe.calls == [], "invalid input still called an agent")

    events = []
    pipe = Pipeline(FULL, FULL)
    original = pipe.extractor
    pipe.extractor = lambda c, y: (events.append("agent_1"), original(c, y))[1]
    result = pipe.run(ingest=lambda: events.append("ingest"))
    expect(events[0] == "ingest" and result["document_processing"]["status"] == "completed",
           "the ingest hook did not run first")
    expect(pipe.run()["document_processing"]["status"] == "skipped", "no hook should mean 'skipped'")

    pipe = Pipeline(FULL, FULL)
    failed = pipe.run(ingest=lambda: (_ for _ in ()).throw(OSError("disk full")))
    expect(failed["status"] == "pipeline_error" and failed["document_processing"]["status"] == "error"
           and pipe.calls == [], "an ingest failure must stop the pipeline before Agent 1")

    order, fakes = [], {}
    for name in ("chunk_documents", "generate_embeddings", "index_chromadb"):
        module = type(sys)(name)
        module.main = (lambda n=name: order.append(n))
        fakes[name] = module
    saved = {n: sys.modules.get(n) for n in fakes}
    sys.modules.update(fakes)
    try:
        orch.index_documents_with_existing_scripts()
    finally:
        for n, m in saved.items():
            sys.modules.pop(n, None) if m is None else sys.modules.__setitem__(n, m)
    expect(order == ["chunk_documents", "generate_embeddings", "index_chromadb"], f"order was {order}")


