def run_all():
    results = []
    for name, kind, categories, function in TESTS:
        try:
            detail = function()
            status, message = "PASS", detail or ""
        except Skip as skip:
            status, message = "SKIP", str(skip)
        except AssertionError as failure:
            status, message = "FAIL", str(failure)
        except Exception as error:
            status, message = "FAIL", f"{type(error).__name__}: {error}"
        results.append((name, kind, categories, status, message))
        print(f"[{status}] ({kind}) {name}")
        if message:
            print(f"        {message}")

    print("\n" + "=" * 62)
    print("MULTI-AGENT VALIDATION SUMMARY")
    print("=" * 62)
    for category in CATEGORY_ORDER:
        related = [r for r in results if category in r[2]]
        print(f"\n{category}:")
        if not related:
            print("   NOT RUN")
            continue
        for kind in dict.fromkeys(r[1] for r in related):
            states = [r[3] for r in related if r[1] == kind]
            overall = ("FAIL" if "FAIL" in states else "SKIPPED" if set(states) == {"SKIP"}
                       else "PASS")
            print(f"   {kind}: {overall}")

    passed = sum(1 for r in results if r[3] == "PASS")
    failed = sum(1 for r in results if r[3] == "FAIL")
    skipped = sum(1 for r in results if r[3] == "SKIP")
    real = [r for r in results if r[1] == "integration (REAL indexed data)"]
    print("\nEnd-to-end pipeline on REAL data: "
          + ("NOT RUN (backend unavailable in this environment)" if real and real[0][3] == "SKIP"
             else real[0][3] if real else "NOT RUN"))
    print(f"\nTests: {passed} passed, {failed} failed, {skipped} skipped")
    if failed:
        print("\nFAILURES:")
        for name, _kind, _categories, status, message in results:
            if status == "FAIL":
                print(f" - {name}\n     {message}")
    return failed == 0


