@test("orchestrator runs Agent 1 -> Agent 2 -> Agent 3 in order", "unit (mock Agent 1)", "Orchestration")
def unit_sequence():
    pipe = Pipeline(FULL, FULL)
    result = pipe.run()
    expect(pipe.calls == [("agent_1", "2023"), ("agent_1", "2024"), ("agent_2",), ("agent_3",)],
           f"unexpected call order {pipe.calls}")
    expect(result["status"] == "success", result["pipeline_errors"])
    expect(result["pipeline_metadata"]["stages_run"] == ["agent_1", "agent_2", "agent_3"], "stages_run wrong")
    no_fail(val.validate_orchestration_result(result))


@test("Agent 1 output is the very object passed to Agent 2", "unit (mock Agent 1)",
      "Agent 1 -> Agent 2 handoff")
def unit_handoff_1_to_2():
    pipe = Pipeline(FULL, DECLINE)
    result = pipe.run()
    previous, current = pipe.agent2_args
    expect(previous is pipe.data["2023"] and current is pipe.data["2024"], "Agent 2 got different objects")
    expect(result["agent_1"]["previous"] is previous and result["agent_1"]["current"] is current,
           "raw Agent 1 records in the result are not the objects Agent 2 received")
    expect(result["agent_2"]["result"]["comparisons"]["revenue"]["current_value"] == 900.0,
           "Agent 2 did not use Agent 1's values")
    no_fail(val.validate_handoffs(result))


@test("Agent 2 output is the very object passed to Agent 3", "unit (mock Agent 1)",
      "Agent 2 -> Agent 3 handoff")
def unit_handoff_2_to_3():
    pipe = Pipeline(FULL, DECLINE)
    result = pipe.run()
    analysis, current, previous = pipe.agent3_args
