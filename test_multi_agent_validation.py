@test("a missing Agent 1 metric does not crash the pipeline", "unit (mock Agent 1)", "Missing-data handling")
def unit_missing_metric():
    previous = {k: v for k, v in FULL.items() if k != "eps"}
    result = Pipeline(previous, FULL).run()
    expect(result["status"] == "success", f"a missing metric must not be a pipeline error: {result['pipeline_errors']}")
    expect(result["pipeline_errors"] == [], "missing data was reported as an error")
    expect(any(l["stage"] == "agent_1" and l["metric"] == "eps" for l in result["limitations"]), "no Agent 1 limitation")
    expect(any(l["stage"] == "agent_2" and l["metric"] == "eps" for l in result["limitations"]), "no Agent 2 limitation")
    expect(not any(f["type"] == "declining_eps" for f in result["agent_3"]["result"]["flags"]), "an EPS flag was invented")
    no_fail(val.validate_handoffs(result))


@test("Agent 1 hard failures (exception, SystemExit, malformed output) are reported",
      "unit (mock Agent 1)", "Error handling")
def unit_agent1_failure():
    for label, kwargs, kind in [("exception", {"fail_agent1": RuntimeError("boom")}, "exception"),
                                ("SystemExit", {"fail_agent1": SystemExit(1)}, "system_exit"),
                                ("malformed", {"agent1_output": ["not", "a", "dict"]}, "malformed_output")]:
        pipe = Pipeline(FULL, FULL, **kwargs)
        result = pipe.run()
        expect(result["status"] == "pipeline_error", f"{label}: status {result['status']}")
        expect(result["pipeline_errors"][0]["stage"] == "agent_1", f"{label}: wrong failed stage")
        expect(result["pipeline_errors"][0]["error_type"] == kind, f"{label}: type {result['pipeline_errors'][0]['error_type']}")
        expect(result["agent_1"]["status"] == "error", f"{label}: agent_1 not marked error")
        expect(result["agent_2"]["status"] == "not_run" and result["agent_3"]["status"] == "not_run",
               f"{label}: a later stage was not marked not_run")
        expect(("agent_2",) not in pipe.calls and ("agent_3",) not in pipe.calls, f"{label}: a later agent still ran")
        no_fail(val.validate_orchestration_result(result), label)


