UNITS = {"revenue": "million USD", "net_income": "million USD", "total_debt": "million USD",
         "cash_flow": "million USD", "eps": "USD per share", "gross_margin": "percent",
         "operating_margin": "percent"}
LABELS = {"revenue": "Revenue", "net_income": "Net Income", "eps": "Earnings Per Share (EPS)",
          "gross_margin": "Gross Margin", "operating_margin": "Operating Margin",
          "total_debt": "Total Debt", "cash_flow": "Cash Flow from Operating Activities"}


def evidence_for(key, value, year):
    columns = f"[columns: Years ended September 30, {year}]"
    return {
        "revenue": f"{columns} ... Total net sales {value:,.0f} 1,000 2,000",
        "net_income": f"{columns} ... Net income $ {value:,.0f} 1,000",
        "eps": f"{columns} ... Earnings per share: Basic $ 9.99 Diluted $ {value:.2f} $ 1.00",
        "gross_margin": f"{columns} ... Total gross margin percentage {value} % 40.0 %",
        "operating_margin": f"{columns} ... Operating margin {value} % 20.0 %",
        "total_debt": f"{columns} ... Total term debt {value:,.0f} 1,000",
        "cash_flow": f"{columns} ... Cash generated by operating activities {value:,.0f} 1,000",
    }[key]


def make_record(company, year, key, value):
    base = {"metric": LABELS[key], "company": company, "fiscal_year": year, "value": None,
            "unit": None, "currency": None, "scale": None, "source_file": None,
            "page_number": None, "evidence": None, "status": "not_found", "score": None,
            "derived": False, "calculation": None, "raw_value": None, "reported_scale": None,
            "column_source": None, "confidence": None, "warnings": []}
    if value is None:
        return base
    unit = UNITS[key]
    money = unit.startswith("million")
    base.update({"value": value, "raw_value": value, "unit": unit,
                 "currency": "USD" if unit != "percent" else None,
                 "scale": "million" if money else None,
                 "reported_scale": "million" if money else None,
                 "source_file": f"{company}_{year}_Annual_report.pdf", "page_number": 32,
                 "evidence": evidence_for(key, value, year), "status": "found", "score": 20.0,
                 "column_source": "year_header", "confidence": "high"})
    return base


def make_year(company, year, values):
    return {key: make_record(company, year, key, values.get(key)) for key in UNITS}


def make_derived_margin(company, year, income, revenue):
    source = f"{company}_{year}_Annual_report.pdf"
    record = make_record(company, year, "operating_margin", round(income / revenue * 100, 2))
    record.update({
        "derived": True, "calculation": "Operating Margin = Operating Income / Revenue * 100",
        "source_file": source, "page_number": 31, "column_source": None,
        "derived_from": [
            {"metric": "Operating Income", "value": income, "unit": "million USD",
             "source_file": source, "page_number": 31},
            {"metric": "Revenue", "value": revenue, "unit": "million USD",
             "source_file": source, "page_number": 31}],
        "evidence": (f"Calculated from Operating Income ({income} million USD, {source} p.31) and "
                     f"Revenue ({revenue} million USD, {source} p.31)."),
    })
    return record


def apple_mock_year(year):
    seed = val.SEED_EXPECTATIONS[("Apple", year)]
    values = {k: seed[k]["value"] for k in ("revenue", "net_income", "eps", "gross_margin")}
    data = make_year("Apple", year, values)
    data["operating_margin"] = make_derived_margin(
        "Apple", year, seed["operating_income"]["value"], seed["revenue"]["value"])
    return data


class Pipeline:
    """Spies around the agents so tests can see what each stage received."""

    def __init__(self, previous_values, current_values, company="TestCo",
                 fail_agent1=None, fail_agent2=None, fail_agent3=None, agent1_output=None):
        self.calls, self.company = [], company
        self.data = {"2023": make_year(company, "2023", previous_values),
                     "2024": make_year(company, "2024", current_values)}
        self.fail = {"1": fail_agent1, "2": fail_agent2, "3": fail_agent3}
        self.agent1_output = agent1_output
        self.agent2_args = self.agent3_args = None

    def extractor(self, company, year):
        self.calls.append(("agent_1", year))
        if self.fail["1"]:
            raise self.fail["1"]
        return self.agent1_output if self.agent1_output is not None else self.data[year]

    def analyzer(self, company, previous_year, current_year, previous_data, current_data):
        self.calls.append(("agent_2",))
        self.agent2_args = (previous_data, current_data)
        if self.fail["2"]:
            raise self.fail["2"]
        return analysis_agent.analyze_company(company, previous_year, current_year,
                                              previous_data, current_data)

    def red_flagger(self, analysis, current_data=None, previous_data=None):
        self.calls.append(("agent_3",))
        self.agent3_args = (analysis, current_data, previous_data)
        if self.fail["3"]:
            raise self.fail["3"]
        return red_flag_agent.build_red_flags(analysis, current_data=current_data,
                                              previous_data=previous_data)

    def run(self, **kwargs):
        return orch.run_financial_analysis(
            self.company, "2023", "2024", extractor=self.extractor, analyzer=self.analyzer,
            red_flagger=self.red_flagger, verbose=False, **kwargs)


