"""
test_multi_agent_validation.py

Tests for the orchestrator (multi_agent_orchestrator.py) and the validation
layer (validate_agent_outputs.py). Every test is labeled with its KIND, because
they prove different things:

  unit (mock Agent 1)            Agent 1 is replaced by hand-made records; Agent 2
                                 and Agent 3 are the REAL agents. Fast, isolated.
                                 Proves orchestration logic, NOT the real pipeline.
  unit (validator)               Feeds good and deliberately bad records to a
                                 validator to prove it passes the good and FAILS the
                                 bad. A validator that cannot fail proves nothing.
  real-output replay             Records rebuilt from the values and evidence
                                 strings printed by YOUR real run of
                                 `python extraction_agent.py`. Not a live database
                                 call, but it checks the validators against real text.
  integration (SIMULATED)        The REAL Agent 1/2/3 code and the REAL orchestrator,
                                 on simulated Apple-shaped pages in a fake ChromaDB.
  integration (REAL indexed data) The real pipeline on your real vectordb/. It is
                                 SKIPPED (not passed) when chromadb,
                                 sentence-transformers or vectordb/ is unavailable.

Run:
    python test_multi_agent_validation.py
"""

