def flags_related_to(red, metric_key, label):
    """Flags that could only exist if this metric's comparison was evaluated."""
    flags = red["flags"]
    if metric_key == "revenue":
        return [f for f in flags if f["type"] == "declining_revenue"]
    if metric_key == "net_income":
        return [f for f in flags if f["type"] == "declining_net_income"]
    if metric_key == "eps":
        return [f for f in flags if f["type"] == "declining_eps"]
    if metric_key in MARGIN_KEYS:
        return [f for f in flags if f["type"] == "margin_compression" and f["metric"] == label]
    if metric_key == "total_debt":
        return [f for f in flags if f["type"] == "rising_debt"]
    if metric_key == "cash_flow":
        return [f for f in flags if f["type"] == "declining_cash_flow"]
    return []


def has_limitation(red, label):
    return any(text.startswith(label) for text in red["data_limitations"])


def check_missing_data_handling(previous_data, current_data, analysis, red):
    """
    Condition 10. Every value that could not be used must show up as a
    limitation, must not produce a related flag, and every calculated
    comparison must rest on values Agent 1 actually found.
    Returns a list of problem strings (empty means the check passed).
    """
    problems = []
    comparisons = analysis["comparisons"]

    for key, label in AGENT2_METRICS:
        comparison = comparisons[key]
        if comparison["status"] == "not_calculated":
            if flags_related_to(red, key, label):
                problems.append(f"{label}: Agent 2 did not calculate it, yet Agent 3 raised a flag.")
            if not has_limitation(red, label):
                problems.append(f"{label}: not calculated but no data limitation was recorded.")
        else:
            needed = ["net_income", "revenue"] if key == "net_profit_margin" else [key]
            for need in needed:
                if not is_found(previous_data.get(need)) or not is_found(current_data.get(need)):
                    problems.append(f"{label}: calculated although Agent 1 had no usable "
                                    f"'{need}' for both years (possible fabrication).")

            # Recompute with Agent 2's own public functions as an independent check.
            previous_value, current_value = comparison["previous_value"], comparison["current_value"]
            if key in MARGIN_KEYS:
                expected = analysis_agent.calculate_margin_change(current_value, previous_value)
                actual = comparison["margin_change_points"]
            else:
                expected = analysis_agent.calculate_percentage_change(current_value, previous_value)
                actual = comparison["percentage_change"]
            if expected != actual:
                problems.append(f"{label}: reported change {actual} does not match recomputed {expected}.")

    for key, label in [("total_debt", "Total Debt"), ("cash_flow", "Cash Flow")]:
        evaluable = red_flag_agent.compute_simple_change(key, current_data, previous_data) is not None
        if not evaluable:
            if flags_related_to(red, key, label):
                problems.append(f"{label}: cannot be evaluated, yet Agent 3 raised a flag.")
            if not has_limitation(red, label):
                problems.append(f"{label}: cannot be evaluated but no data limitation was recorded.")

    if not is_found(current_data.get("cash_flow")):
        if any(f["type"] == "negative_cash_flow" for f in red["flags"]):
            problems.append("Cash Flow: negative_cash_flow flag raised without a current-year value.")

    needs = {"Revenue / Net Income": ["revenue", "net_income"],
             "Revenue / Operating Margin": ["revenue", "operating_margin"],
             "EPS / Revenue": ["eps", "revenue"]}
    for flag in red["flags"]:
        if flag["type"] == "unusual_pattern":
            for key in needs.get(flag["metric"], []):
                if comparisons[key]["status"] != "calculated":
                    problems.append(f"Unusual-pattern flag '{flag['metric']}' depends on '{key}', "
                                    f"which was not calculated.")
        if flag["type"] == "debt_rising_profitability_declining":
            if comparisons["net_income"]["status"] != "calculated" or \
                    red_flag_agent.compute_simple_change("total_debt", current_data, previous_data) is None:
                problems.append("Debt-vs-profitability flag raised without both inputs available.")
    return problems


def find_recommendation_wording(analysis, red):
    generated = [analysis.get("summary", ""), analysis_agent.format_report(analysis),
                 red.get("summary", ""), red_flag_agent.format_red_flag_report(red)]
    generated += [flag["description"] for flag in red["flags"]]
    hits = set()
    for text in generated:
        hits.update(match.group(0).lower() for match in RECOMMENDATION_PATTERN.finditer(text))
    return sorted(hits)


