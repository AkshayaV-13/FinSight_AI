def print_agent1(company, previous_year, current_year, previous_data, current_data):
    banner("AGENT 1")
    for key, label in AGENT1_METRICS:
        print(f"{label}")
        print(f"  FY{previous_year}: {describe_record((previous_data or {}).get(key))}")
        print(f"  FY{current_year}: {describe_record((current_data or {}).get(key))}")


def print_agent2(analysis):
    banner("AGENT 2")
    for key, label in AGENT2_METRICS:
        comparison = analysis["comparisons"][key]
        print(f"{label}: {comparison['status']}")
        if comparison["status"] != "calculated":
            print(f"  reason: {comparison.get('reason')}")
            continue
        unit = comparison.get("unit") or ""
        print(f"  Previous: {comparison['previous_value']} {unit}".rstrip())
        print(f"  Current:  {comparison['current_value']} {unit}".rstrip())
        if key in MARGIN_KEYS:
            print(f"  Change:   {comparison['margin_change_points']:+} percentage points"
                  + ("  [derived]" if comparison.get("derived") else ""))
        else:
            print(f"  Change:   {comparison['change']:+} {unit}".rstrip())
            print(f"  Percentage change: {comparison['percentage_change']}%")
        print(f"  Direction: {comparison['direction']}")


def print_agent3(red):
    banner("AGENT 3")
    if not red["flags"]:
        print("No flags were raised.")
    for index, flag in enumerate(red["flags"], start=1):
        change = (f"{flag['change_percent']}%" if flag["change_percent"] is not None
                  else f"{flag['change_points']} percentage points" if flag["change_points"] is not None
                  else "n/a")
        print(f"[{index}] {flag['type']}  severity={flag['severity']}")
        print(f"    metric:   {flag['metric']}")
        print(f"    previous: {flag['previous_value']}   current: {flag['current_value']}   change: {change}")
        print(f"    {flag['description']}")
        if flag["source_file"]:
            print(f"    source:   {flag['source_file']} (page {flag['page_number']})")
        else:
            print("    source:   not available")
    print("\nData limitations:")
    for text in red["data_limitations"] or ["(none)"]:
        print(f"  - {text}")
    print(f"\nNumber of flags: {len(red['flags'])}")


def print_propagation(previous_year, current_year, previous_data, current_data, analysis, red):
    """Show how each Agent 1 gap travelled through the pipeline."""
    banner("MISSING-DATA PROPAGATION")
    comparisons = analysis["comparisons"]
    shown = False
    for key, label in AGENT1_METRICS:
        previous_ok = is_found(previous_data.get(key))
        current_ok = is_found(current_data.get(key))
        if previous_ok and current_ok:
            continue
        shown = True
        print(f"{label}: FY{previous_year} {'found' if previous_ok else 'NOT_FOUND'}, "
              f"FY{current_year} {'found' if current_ok else 'NOT_FOUND'}")
        if key in comparisons:
            print(f"  -> Agent 2: comparison {comparisons[key]['status']}")
        else:
            print("  -> Agent 2: does not compare this metric")
        related = flags_related_to(red, key, label)
        print(f"  -> Agent 3: {label}-related flag "
              f"{'RAISED (unexpected)' if related else 'not evaluated'}")
        print(f"  -> Data limitation recorded: {'yes' if has_limitation(red, label) else 'NO'}")
    if not shown:
        print("Agent 1 found every metric for both years; nothing to propagate.")


