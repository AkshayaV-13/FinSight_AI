# Wording that would indicate advice or ranking. Only text GENERATED by
# Agent 2 / Agent 3 is scanned, never the raw annual-report evidence.
RECOMMENDATION_PATTERN = re.compile(
    r"\b(buy|sell|should invest|recommend\w*|best|worst|winner|loser|"
    r"good investment|bad investment|avoid investing|overvalued|undervalued)\b",
    re.IGNORECASE,
)

