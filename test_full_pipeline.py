def main(company="Apple", previous_year="2023", current_year="2024"):
    print("=" * 60)
    print("FULL PIPELINE TEST")
    print()
    print(f"Company: {company}")
    print(f"Previous Year: FY{previous_year}")
    print(f"Current Year: FY{current_year}")

    if IMPORT_ERROR is not None:
        PIPELINE_ERRORS.append(f"Could not import the agents: {type(IMPORT_ERROR).__name__}: {IMPORT_ERROR}")
        return finish({})

    print("\nInspected signatures:")
    for module, name in [(extraction_agent, "extract_metrics"), (analysis_agent, "analyze_company"),
                         (red_flag_agent, "build_red_flags")]:
        print(f"  {module.__name__}.{name}{inspect.signature(getattr(module, name))}")

    status = {"agent1": False, "agent2": False, "agent3": False}
    conditions = {}

    # ---- Agent 1 ------------------------------------------------------
    previous_data, error_previous = run_stage("Agent 1 (previous year)", extraction_agent.extract_metrics,
                                              company, previous_year)
    current_data, error_current = run_stage("Agent 1 (current year)", extraction_agent.extract_metrics,
                                            company, current_year)
    for error in (error_previous, error_current):
        if error:
            PIPELINE_ERRORS.append(error)

    print_agent1(company, previous_year, current_year, previous_data, current_data)

    agent1_problems = []
    if previous_data is not None:
        agent1_problems += validate_agent1_output(previous_data, previous_year)
    if current_data is not None:
        agent1_problems += validate_agent1_output(current_data, current_year)
    PIPELINE_ERRORS.extend(agent1_problems)

    conditions[1] = ("Agent 1 returned a dictionary",
                     isinstance(previous_data, dict) and isinstance(current_data, dict) and not agent1_problems)
    status["agent1"] = conditions[1][1]

    if status["agent1"]:
        for key, label in AGENT1_METRICS:
            for year, data in ((previous_year, previous_data), (current_year, current_data)):
                if not is_found(data.get(key)):
                    EXPECTED_LIMITATIONS.append(f"{label}: Agent 1 returned NOT_FOUND for FY{year}.")
        for year, data in ((previous_year, previous_data), (current_year, current_data)):
            if not any(is_found(data.get(key)) for key, _ in AGENT1_METRICS):
                print(f"\nNOTE: Agent 1 found NO metric at all for FY{year}. That pattern usually "
                      f"means the company / fiscal_year metadata filter matched no chunks (for example "
                      f"a company name or year tagged differently in the index), not that the "
                      f"report lacks the numbers.")

    # ---- Agent 2 and Agent 3 ------------------------------------------
    analysis = red = None
    counter = None
    model_before = collection_before = None

    if status["agent1"]:
        model_before = getattr(extraction_agent, "_model", None)
        collection_before = getattr(extraction_agent, "_collection", None)

        with CallCounter(extraction_agent) as counter:
            analysis, error = run_stage("Agent 2", analysis_agent.analyze_company, company,
                                        previous_year, current_year, previous_data, current_data)
            if error:
                PIPELINE_ERRORS.append(error)
            else:
                agent2_problems = validate_agent2_output(analysis)
                PIPELINE_ERRORS.extend(agent2_problems)
                if agent2_problems:
                    analysis = None

            if analysis is not None:
                red, error = run_stage("Agent 3", red_flag_agent.build_red_flags, analysis,
                                       current_data=current_data, previous_data=previous_data)
                if error:
                    PIPELINE_ERRORS.append(error)
                else:
                    agent3_problems = validate_agent3_output(red)
                    PIPELINE_ERRORS.extend(agent3_problems)
                    if agent3_problems:
                        red = None

        if analysis is not None:
            print_agent2(analysis)
        if red is not None:
            print_agent3(red)
            print_propagation(previous_year, current_year, previous_data, current_data, analysis, red)

    conditions[2] = ("Agent 2 successfully consumed Agent 1 output", analysis is not None)
    conditions[3] = ("Agent 2 returned a structured analysis result", analysis is not None)
    conditions[4] = ("Agent 3 successfully consumed Agent 2 output", red is not None)
    conditions[5] = ("Agent 3 returned a structured red-flag result", red is not None)
    conditions[6] = ("No agent raised an unexpected exception", not PIPELINE_ERRORS)

    # ---- Conditions 7 and 8: no ChromaDB access / no model load in Agents 2-3
    static_problems = (static_import_check(analysis_agent, allow_lazy_agent1_in=("analyze_company_live",))
                       + static_import_check(red_flag_agent))
    for problem in static_problems:
        PIPELINE_ERRORS.append(f"Static import check: {problem}")

    dynamic_note = "agents did not run, so only the static import check was possible"
    retrieval_calls = model_loads = 0
    if counter is not None and analysis is not None:
        retrieval_calls = sum(counter.counts.get(n, 0) for n in
                              ("get_collection", "retrieve_chunks", "retrieve_chunks_multi",
                               "build_metric_record", "build_operating_margin", "extract_metrics"))
        model_loads = counter.counts.get("get_model", 0)
        if getattr(extraction_agent, "_model", None) is not model_before:
            model_loads += 1
        if getattr(extraction_agent, "_collection", None) is not collection_before:
            retrieval_calls += 1
        dynamic_note = (f"{retrieval_calls} Agent 1 retrieval/extraction call(s) and "
                        f"{model_loads} model load(s) while Agents 2-3 ran")

    conditions[7] = (f"No ChromaDB access inside Agent 2 or Agent 3 ({dynamic_note})",
                     not static_problems and retrieval_calls == 0)
    conditions[8] = (f"No embedding model loaded by Agent 2 or Agent 3 ({dynamic_note})",
                     not static_problems and model_loads == 0)
    if retrieval_calls or model_loads:
        PIPELINE_ERRORS.append("Agent 2 or Agent 3 triggered Agent 1 retrieval or a model load.")

    # ---- Conditions 9 and 10 -------------------------------------------
    if analysis is not None and red is not None:
        hits = find_recommendation_wording(analysis, red)
        conditions[9] = ("No investment recommendation is produced"
                         + (f" (found wording: {hits})" if hits else ""), not hits)
        if hits:
            PIPELINE_ERRORS.append(f"Recommendation-style wording found in Agent 2/3 output: {hits}")

        missing_problems = check_missing_data_handling(previous_data, current_data, analysis, red)
        PIPELINE_ERRORS.extend(missing_problems)
        conditions[10] = ("Missing Agent 1 data is reported as a limitation, not fabricated",
                          not missing_problems)
    else:
        conditions[9] = ("No investment recommendation is produced (not checked: agents did not run)", None)
        conditions[10] = ("Missing data reported, not fabricated (not checked: agents did not run)", None)

    status["agent2"] = analysis is not None and conditions[10][1] is not False
    status["agent3"] = red is not None and conditions[9][1] is not False and conditions[10][1] is not False

    banner("FINAL VALIDATION")
    for number in sorted(conditions):
        description, passed = conditions[number]
        outcome = "NOT CHECKED" if passed is None else ("PASS" if passed else "FAIL")
        print(f"  {number:>2}. [{outcome}] {description}")

    return finish(status)


def finish(status):
    agent1 = status.get("agent1", False)
    agent2 = status.get("agent2", False)
    agent3 = status.get("agent3", False)
    end_to_end = agent1 and agent2 and agent3 and not PIPELINE_ERRORS

    print("\n" + "=" * 60)
    print("PIPELINE ERRORS (something is broken)")
    for text in PIPELINE_ERRORS or ["(none)"]:
        print(f"  - {text}")

    print("\nEXPECTED DATA LIMITATIONS (Agent 1 gaps, handled correctly)")
    for text in EXPECTED_LIMITATIONS or ["(none)"]:
        print(f"  - {text}")

    print("\n" + "=" * 60)
    print("PIPELINE TEST SUMMARY")
    print()
    print(f"Agent 1: {'PASS' if agent1 else 'FAIL'}")
    print(f"Agent 2: {'PASS' if agent2 else 'FAIL'}")
    print(f"Agent 3: {'PASS' if agent3 else 'FAIL'}")
    print(f"End-to-end pipeline: {'PASS' if end_to_end else 'FAIL'}")
    print()
    print("Command to run this test:  python test_full_pipeline.py")
    return 0 if end_to_end else 1


