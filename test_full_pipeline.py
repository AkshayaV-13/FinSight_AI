def banner(title):
    print("\n" + "-" * 16 + f" {title} " + "-" * max(4, 44 - len(title)))


def describe_record(record):
    """One readable line for an Agent 1 record."""
    if record is None:
        return "MISSING (no record returned)"
    if not is_found(record):
        return "NOT_FOUND"
    text = f"{record.get('value')} {record.get('unit') or ''}".strip()
    if record.get("derived"):
        text += "  [derived]"
    if record.get("source_file"):
        text += f"  (page {record.get('page_number')}, {record['source_file']})"
    return text


def imported_module_names(tree):
    names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names.update(alias.name.split(".")[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            names.add(node.module.split(".")[0])
    return names


def static_import_check(module, allow_lazy_agent1_in=()):
    """
    Read a module's source and list forbidden imports. chromadb and
    sentence_transformers are never allowed. extraction_agent is not allowed
    at module level; it may appear inside the named functions only.
    """
    problems = []
    tree = ast.parse(inspect.getsource(module))

    forbidden = imported_module_names(tree) & {"chromadb", "sentence_transformers"}
    if forbidden:
        problems.append(f"{module.__name__} imports {sorted(forbidden)}")

    module_level = ast.Module(
        body=[n for n in tree.body if isinstance(n, (ast.Import, ast.ImportFrom))],
        type_ignores=[],
    )
    if "extraction_agent" in imported_module_names(module_level):
        problems.append(f"{module.__name__} imports extraction_agent at module level")

    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name not in allow_lazy_agent1_in:
            if "extraction_agent" in imported_module_names(node):
                problems.append(f"{module.__name__}.{node.name}() imports extraction_agent")
    return problems


class CallCounter:
    """
    Temporarily wraps Agent 1's retrieval / extraction functions so any call
    made while Agent 2 or Agent 3 is running is counted. The wrapped
    function still runs normally.
    """
    NAMES = ["get_model", "get_collection", "retrieve_chunks", "retrieve_chunks_multi",
             "build_metric_record", "build_operating_margin", "extract_metrics"]

    def __init__(self, module):
        self.module = module
        self.counts = {}
        self._originals = {}

    def __enter__(self):
        for name in self.NAMES:
            original = getattr(self.module, name, None)
            if original is None:
                continue
            self._originals[name] = original
            self.counts[name] = 0

            def wrapper(*args, _name=name, _original=original, **kwargs):
                self.counts[_name] += 1
                return _original(*args, **kwargs)

            setattr(self.module, name, wrapper)
        return self

    def __exit__(self, *exc_info):
        for name, original in self._originals.items():
            setattr(self.module, name, original)
        return False

    def total(self):
        return sum(self.counts.values())


# ---------------------------------------------------------------------------
# Stage runners. Each one catches SystemExit as well as Exception, because
# extraction_agent calls sys.exit(1) when a dependency or the database is
# missing, and that would otherwise silently end this whole script.
# ---------------------------------------------------------------------------

def run_stage(label, function, *args, **kwargs):
    """Run one agent call. Returns (result, None) or (None, error_text)."""
    try:
        return function(*args, **kwargs), None
    except SystemExit as stop:
        return None, (f"{label}: the agent stopped the process (SystemExit {stop.code}). "
                      f"For Agent 1 this usually means a missing package, a missing vectordb/ "
                      f"folder, or a missing 'financial_documents' collection; read the "
                      f"message printed just above.")
    except Exception as error:
        return None, f"{label}: {type(error).__name__}: {error}"


def validate_agent1_output(data, year):
    problems = []
    if not isinstance(data, dict):
        return [f"Agent 1 output for FY{year} is {type(data).__name__}, not a dict."]
    for key, _ in AGENT1_METRICS:
        record = data.get(key)
        if not isinstance(record, dict):
            problems.append(f"FY{year}: no record dict for '{key}'.")
        elif "status" not in record:
            problems.append(f"FY{year}: record for '{key}' has no 'status' field.")
    return problems


def validate_agent2_output(analysis):
    problems = []
    if not isinstance(analysis, dict):
        return [f"Agent 2 output is {type(analysis).__name__}, not a dict."]
    for key in ("company", "previous_year", "current_year", "comparisons", "summary"):
        if key not in analysis:
            problems.append(f"Agent 2 result is missing '{key}'.")
    comparisons = analysis.get("comparisons")
    if not isinstance(comparisons, dict):
        return problems + ["Agent 2 'comparisons' is not a dict."]
    for key, _ in AGENT2_METRICS:
        comparison = comparisons.get(key)
        if not isinstance(comparison, dict):
            problems.append(f"Agent 2 has no comparison for '{key}'.")
        elif comparison.get("status") not in ("calculated", "not_calculated"):
            problems.append(f"Agent 2 comparison '{key}' has unexpected status "
                            f"{comparison.get('status')!r}.")
    return problems


def validate_agent3_output(red):
    problems = []
    if not isinstance(red, dict):
        return [f"Agent 3 output is {type(red).__name__}, not a dict."]
    for key in ("company", "fiscal_years", "flags", "summary", "data_limitations"):
        if key not in red:
            problems.append(f"Agent 3 result is missing '{key}'.")
    if not isinstance(red.get("flags"), list):
        return problems + ["Agent 3 'flags' is not a list."]
    for index, flag in enumerate(red["flags"], start=1):
        missing = [k for k in FLAG_REQUIRED_KEYS if k not in flag]
        if missing:
            problems.append(f"Agent 3 flag #{index} is missing fields: {missing}")
    return problems


