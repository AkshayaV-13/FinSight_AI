"""
test_full_pipeline.py

End-to-end integration test:

    REAL ChromaDB / annual-report data
        -> Agent 1  extraction_agent.extract_metrics()
        -> Agent 2  analysis_agent.analyze_company()
        -> Agent 3  red_flag_agent.build_red_flags()
        -> final structured red-flag output

Purpose: prove the three agents can pass real data to each other. It tests
PIPELINE COMMUNICATION, not whether Agent 1 is currently perfect, so a
metric that Agent 1 reports as NOT_FOUND is NOT a failure. Every problem
found is sorted into exactly one of two buckets and both are always shown:

    PIPELINE ERROR            something broke: an exception, a wrong data
                              shape, or a missing value that was silently
                              dropped or fabricated instead of reported
    EXPECTED DATA LIMITATION  Agent 1 could not find a value; the pipeline
                              handled it correctly by not calculating and
                              by recording a limitation

This file only calls the existing public functions. It does not modify any
agent, ChromaDB, the embeddings, or the chunking code.

Run (defaults to Apple FY2023 -> FY2024):
    python test_full_pipeline.py

Optional arguments for other companies:
    python test_full_pipeline.py Microsoft 2023 2024
"""

