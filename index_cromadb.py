"""
index_chromadb.py

ChromaDB indexing stage of the Document Agent.

What this script does
----------------------
1. Reads every *_embeddings.json file in embeddings/
2. Opens (or creates) a persistent local ChromaDB database at vectordb/
3. Adds each chunk to the "financial_documents" collection using the
   embedding vector that was already generated by generate_embeddings.py

What this script deliberately does NOT do
------------------------------------------
- It does not generate any new embeddings. ChromaDB's default embedding
  function is never invoked; every vector passed to it comes straight from
  the embeddings/*.json files.
- It does not touch data/annual_reports/, documents/, chunks/, or
  embeddings/. Those folders are only read, never written.
- It does not run any retrieval/search queries. That is the next step.

Duplicate protection / resumability
------------------------------------
Before inserting, the script fetches the set of chunk_ids already present
in the collection and skips any record whose id is already indexed. This
means:
  - running the script twice does not create duplicate records
  - if the script is interrupted partway through, re-running it picks up
    only the records that were not yet added

Usage (PowerShell):
    python index_chromadb.py
"""

import json
import sys
import time
from pathlib import Path

# ---------------------------------------------------------------------------
# Paths and settings
# ---------------------------------------------------------------------------
PROJECT_ROOT = Path(__file__).resolve().parent
EMBEDDINGS_DIR = PROJECT_ROOT / "embeddings"
VECTORDB_DIR = PROJECT_ROOT / "vectordb"

COLLECTION_NAME = "financial_documents"
BATCH_SIZE = 200  # how many records are sent to ChromaDB per add() call


def load_embedding_files():
    """Return a sorted list of every *_embeddings.json file in embeddings/."""
    files = sorted(EMBEDDINGS_DIR.glob("*_embeddings.json"))
    if not files:
        print(f"No embedding files found in {EMBEDDINGS_DIR}")
        print("Run generate_embeddings.py first.")
        sys.exit(1)
    return files


def load_all_records(embedding_files):
    """
    Load and combine every record from every embeddings file.

    Each record is expected to look like:
        {"chunk_id": "...", "text": "...", "metadata": {...}, "embedding": [...]}

    Malformed records (missing a required field) are counted and skipped
    rather than stopping the whole run.
    """
    all_records = []
    skipped = 0

    for path in embedding_files:
        try:
            with open(path, "r", encoding="utf-8") as f:
                records = json.load(f)
        except (json.JSONDecodeError, OSError) as exc:
            print(f"   [ERROR] Could not read {path.name}: {exc}. Skipping this file.")
            continue

        good_in_file = 0
        for record in records:
            if not all(k in record for k in ("chunk_id", "text", "embedding")):
                skipped += 1
                continue
            all_records.append(record)
            good_in_file += 1

        print(f"   {path.name:<55} -> {good_in_file} chunk(s)")

    if skipped:
        print(f"\n[WARNING] {skipped} record(s) across all files were missing a "
              f"required field (chunk_id/text/embedding) and were skipped.")

    return all_records


def get_chromadb_client_and_collection():
    """
    Open (or create) the persistent ChromaDB client and collection.

    Fails with a clear message if chromadb is not installed.
    """
    try:
        import chromadb
    except ImportError:
        print("chromadb is not installed.")
        print("Install it first with:")
        print("    pip install chromadb")
        sys.exit(1)

    VECTORDB_DIR.mkdir(parents=True, exist_ok=True)

    client = chromadb.PersistentClient(path=str(VECTORDB_DIR))

    # Cosine distance is the standard choice for sentence-transformers
    # embeddings like all-MiniLM-L6-v2.
    collection = client.get_or_create_collection(
        name=COLLECTION_NAME,
        metadata={"hnsw:space": "cosine"},
    )
    return client, collection


def get_already_indexed_ids(collection):
    """
    Fetch every chunk_id currently stored in the collection.

    We only ask for ids (include=[]) to keep this fast even once the
    collection holds thousands of records.
    """
    existing = collection.get(include=[])
    return set(existing.get("ids", []))


def sanitize_metadata(metadata):
    """
    ChromaDB metadata values must be str, int, float, or bool.

    Any value that is None or an unsupported type (e.g. a nested dict or
    list, which should not normally appear here) is converted to a string
    so a single odd value cannot crash the whole batch.
    """
    clean = {}
    for key, value in (metadata or {}).items():
        if value is None:
            clean[key] = "unknown"
        elif isinstance(value, (str, int, float, bool)):
            clean[key] = value
        else:
            clean[key] = str(value)
    return clean


def index_records(collection, records):
    """
    Add records to the collection in batches, skipping any chunk_id that
    is already indexed.

    Returns (added_count, skipped_count, error_count).
    """
    existing_ids = get_already_indexed_ids(collection)
    print(f"\nCollection already contains {len(existing_ids)} record(s).")

    pending = [r for r in records if r["chunk_id"] not in existing_ids]
    already_done = len(records) - len(pending)

    if already_done:
        print(f"{already_done} record(s) are already indexed and will be skipped.")

    if not pending:
        print("Nothing new to index.")
        return 0, already_done, 0

    total_batches = (len(pending) + BATCH_SIZE - 1) // BATCH_SIZE
    added = 0
    errors = 0

    for batch_num in range(total_batches):
        start = batch_num * BATCH_SIZE
        end = start + BATCH_SIZE
        batch = pending[start:end]

        ids = [r["chunk_id"] for r in batch]
        documents = [r["text"] for r in batch]
        embeddings = [r["embedding"] for r in batch]
        metadatas = [sanitize_metadata(r.get("metadata", {})) for r in batch]

        print(f"Indexing batch {batch_num + 1}/{total_batches} "
              f"({len(batch)} records)...", end=" ")

        try:
            # add() (not upsert()) is used deliberately: pending already
            # excludes every chunk_id that exists, so add() is enough and
            # will raise if something slips through, rather than silently
            # overwriting an existing record.
            collection.add(
                ids=ids,
                documents=documents,
                embeddings=embeddings,
                metadatas=metadatas,
            )
            added += len(batch)
            print("done")
        except Exception as exc:
            print(f"FAILED ({exc})")
            errors += len(batch)

    return added, already_done, errors


def main():
    start_time = time.time()

    print("Looking for embedding files...")
    embedding_files = load_embedding_files()
    print(f"Found {len(embedding_files)} embedding file(s)\n")

    print("Loading...")
    records = load_all_records(embedding_files)
    print(f"\nLoaded {len(records)} chunk record(s) total.\n")

    client, collection = get_chromadb_client_and_collection()

    added, skipped, errors = index_records(collection, records)

    elapsed = time.time() - start_time

    print("\n" + "=" * 60)
    print("INDEXING COMPLETE")
    print("=" * 60)
    print(f"Newly added     : {added}")
    print(f"Already indexed : {skipped} (skipped)")
    print(f"Failed batches  : {errors}")
    print(f"Time taken      : {elapsed:.1f} seconds")

    print("\n--- Verification ---")
    print(f"Collection name : {collection.name}")
    print(f"Record count    : {collection.count()}")
    print(f"Database path   : {VECTORDB_DIR}")


if __name__ == "__main__":
    main()