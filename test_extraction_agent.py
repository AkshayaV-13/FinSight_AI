# Fake sentence-transformers + ChromaDB (no network, no real database)
# ---------------------------------------------------------------------------
_STATE = {"pages": [], "last_query": ""}
_STOPWORDS = {"the", "of", "and", "in", "for", "to", "a", "an"}


def _tokens(text):
    return {t for t in re.findall(r"[a-z]+", text.lower()) if t not in _STOPWORDS}


class _FakeModel:
    def encode(self, texts, normalize_embeddings, convert_to_numpy):
        _STATE["last_query"] = texts[0]
        return np.array([[0.1, 0.2, 0.3]])


class _FakeCollection:
    def query(self, query_embeddings, n_results, where, include):
        conditions = where.get("$and", [where]) if where else []
        wanted = {k: v for c in conditions for k, v in c.items()}
        pool = [p for p in _STATE["pages"]
                if all(p.get(k) == v for k, v in wanted.items())]
        query_tokens = _tokens(_STATE["last_query"])
        ranked = sorted(
            pool, key=lambda p: -len(query_tokens & _tokens(p["text"])))[:n_results]
        docs = [p["text"] for p in ranked]
        metas = [{"company": p["company"], "fiscal_year": p["fiscal_year"],
                  "source_file": p["source_file"], "page_number": p["page_number"]}
                 for p in ranked]
        dists = [round(1 - len(query_tokens & _tokens(p["text"])) / max(1, len(query_tokens)), 4)
                 for p in ranked]
        return {"documents": [docs], "metadatas": [metas], "distances": [dists]}


class _FakeClient:
    def __init__(self, path):
        pass

    def get_collection(self, name):
        return _FakeCollection()


def install_fake_backend(pages):
    """Point extraction_agent at the simulated pages. Nothing real is touched."""
    st = types.ModuleType("sentence_transformers")
    st.SentenceTransformer = lambda name: _FakeModel()
    sys.modules["sentence_transformers"] = st
    chroma = types.ModuleType("chromadb")
    chroma.PersistentClient = lambda path: _FakeClient(path)
    sys.modules["chromadb"] = chroma

    import extraction_agent as ea
    _STATE["pages"] = pages
    ea._collection = None
    ea._model = None
    ea.VECTORDB_DIR = ea.PROJECT_ROOT
    ea.clear_context_cache()
    return ea


def check(label, condition):
    print(f"  [{'PASS' if condition else 'FAIL'}] {label}")
    return bool(condition)


